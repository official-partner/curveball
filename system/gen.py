# Generates src/styles/base.css from system/curveball.json and the starter's reset (system/reset.css).
# Run: python3 -I system/gen.py   (never edit base.css by hand)
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
S = json.load(open(os.path.join(HERE, 'curveball.json')))
V = S['viewport']; R = V['reference']; DMIN = V['desktopMin']


def num(x):
    return ('%.3f' % x).rstrip('0').rstrip('.')


def formula(n):
    return (f"clamp(var(--{n}-min) / 16 * 1rem, ((var(--{n}-min) - ((var(--{n}-max) - var(--{n}-min)) / "
            f"(var(--viewport-max) - var(--viewport-min)) * var(--viewport-min))) / 16 * 1rem + ((var(--{n}-max) - "
            f"var(--{n}-min)) / (var(--viewport-max) - var(--viewport-min))) * 100vw), var(--{n}-max) / 16 * 1rem)")


NOWRAP = ()
out = []
w = out.append
w("/* Design tokens: GENERATED by system/gen.py from system/curveball.json. Do not edit by hand. */")
w(f"/* {S['fonts']['note']} The licence is bought before the site goes live. */")
for f in S['fonts']['files']:
    w('@font-face {\n  font-family: "ES Build";\n  src: url("/fonts/%s") format("woff2");\n  font-weight: %d;\n'
      '  font-style: normal;\n  font-display: block;\n}' % (f['file'], f['weight']))
w(":root {")
w("  /* Swatches: the brand guide's palette, and the Figma's taupe */")
for k, v in S['swatches'].items():
    w(f"  --{k}: {v['hex']};")
w("  /* Tones: the Figma's opacities of the text colour */")
w("  --tone-strong: 100%;\n  --tone-muted: 50%;\n  --tone-faint: 30%;")
w("  /* The page's own colour (red on Home, mustard on News, teal on Contact): the footer's mark, the ball and the\n"
  "     curve take it. A page sets it with .accent-* on its body (themes never reset it). */")
w("  --page-accent: var(--red);")
w("\n  /* Typography primitives */")
w(f"  --es-build: {S['fonts']['family']};")
w("  /* ES Build's cap height (682 of 1000): to centre a mark on the capitals of a trimmed text box */\n  --cap-height: 0.682em;")
w("  --primary-family: var(--es-build);\n  --mono-family: ui-monospace, \"SF Mono\", SFMono-Regular, Menlo, Consolas, monospace;")
w("  --primary-regular: 400;\n  --primary-medium: 500;\n  --primary-bold: 700;")
w("  --letter-spacing-tight: -0.03em;\n  --letter-spacing-normal: 0em;")
w("  --line-height-small: 0.91;\n  --line-height-medium: 1.1;\n  --line-height-large: 1.2;\n  --line-height-huge: 1.5;")
w("\n  /* Borders & focus */\n  --border-width: 0.0625rem;\n  --focus-width: 0.125rem;\n  --focus-offset: 0.1827rem;\n"
  "  --focus-offset-inner: calc(var(--focus-width) * -1);")
w("\n  /* Motion: OP's named durations and curves. Productive (what answers the person) on the out curve, expressive\n"
  "     (what is watched) on the arrive curve; leaving takes about 60 % of arriving. */")
w("  --duration-faster: 150ms;\n  --duration-fast: 250ms;\n  --duration-medium: 450ms;\n  --duration-base: 800ms;\n"
  "  --duration-slow: 1200ms;\n  --ease-out: cubic-bezier(0.23, 1, 0.32, 1);\n  --ease-arrive: cubic-bezier(0.625, 0.05, 0, 1);")
w("  --hover-duration: var(--duration-fast);\n  --hover-ease: var(--ease-out);\n  --open-duration: var(--duration-medium);\n"
  "  --open-ease: var(--ease-out);\n  --loader-duration: 600ms;\n  --loader-ease: var(--ease-arrive);\n"
  "  --page-leave-duration: var(--duration-medium);\n  --page-leave-ease: var(--ease-out);\n  --page-arrive-duration: var(--duration-base);\n"
  "  --page-arrive-ease: var(--ease-arrive);")
w("  --ease-smooth: cubic-bezier(0.16, 1, 0.3, 1);\n  --ease-osmo: var(--ease-arrive);\n  --ease-rebound: cubic-bezier(0.34, 1.56, 0.64, 1);")
w("\n  /* Radius: the design has no rounded corner but full circles (the photos, the ball, the dot) */")
w("  --radius-small: 0rem;\n  --radius-main: 0rem;\n  --radius-round: 100vw;")
w(f"\n  /* Fluid scale range: phone {V['phone']} to tablet {V['tabletMax']}; the computer range is in the 64rem block */")
w(f"  --viewport-min: {V['phone']};\n  --viewport-max: {V['tabletMax']};")
w("\n  /* Max width: the content width at the reference width; nothing grows beyond it */")
w("  --max-width-small: 70rem;\n  --max-width-main: calc((var(--viewport-max) - 2 * var(--site-margin-max)) / 16 * 1rem);\n"
  "  --max-width-full: 100%;")
w("\n  /* Nav: the logo between two margins */\n  --nav-height: calc(var(--logo-size) + var(--site-margin) * 2);")
w("\n  /* Fluid tokens: phone and tablet values here, the computer's in the 64rem block */")
for n, (ph, tb, dk) in S['fluid'].items():
    w(f"  --{n}: {formula(n)};")
    w(f"  --{n}-min: {num(ph)};\n  --{n}-max: {num(tb)};")
w("\n  /* Role tokens: one job each, pointing at a step of the scale (change the step, every use follows) */")
for n, r in S.get('roles', {}).items():
    w(f"  /* {r['job']} */")
    w(f"  --{n}: var(--{r['ref']});")
w("\n  /* Floors: reading text and small parts stop shrinking here (applied with max() where they are used) */")
for n, f in S['floors'].items():
    w(f"  --{n}-floor: {num(f / 16)}rem;")
w("\n  /* Text style properties */")
for n, t in S['text'].items():
    wrap = 'nowrap' if n in NOWRAP else 'pretty'
    w(f"  --{n}-line-height: {t['lh']};\n  --{n}-letter-spacing: {t['ls']};\n  --{n}-text-transform: {t['tt']};\n"
      f"  --{n}-font-family: var(--es-build);\n  --{n}-font-weight: {t['weight']};\n  --{n}-margin-top: 0rem;\n"
      f"  --{n}-margin-bottom: 0rem;\n  --{n}-text-wrap: {wrap};")
w("\n  /* The design unit: one Figma pixel at 1728, scaled with the page's width (main is the container, so the scrollbar is\n     left out). Only for the art-directed parts that scale as one piece: the curves, the ball, the footer's symbol. */")
w("  --u: calc(100cqw / 1728);")
w("\n  /* Site layout */\n  --site-width: calc(100% - var(--site-margin) * 2);\n"
  "  /* The layout grid's columns: phone here, tablet and computer in the media blocks */\n  --site-columns: 4;")
w("}")
phone_roles = {n: r['phone'] for n, r in S.get('roles', {}).items() if r.get('phone')}
if phone_roles:
    w("/* Phone: role tokens that point at another step below the tablet */\n@media (width < 48rem) {\n  :root {")
    for n, ref in phone_roles.items():
        w(f"    --{n}: var(--{ref});")
    w("  }\n}")
w("/* Tablet: 8 columns (Lumos Grid breakpoint 48rem) */\n@media (width >= 48rem) {\n  :root {\n    --site-columns: 8;\n  }\n}")
w(f"/* Computer, {DMIN} to {R}: everything scales with the grid. Each -min is -max x {DMIN} / {R}. */")
w("@media (width >= 64rem) {\n  :root {\n    --site-columns: 12;")
w(f"    --viewport-min: {DMIN};\n    --viewport-max: {R};")
for n, (ph, tb, dk) in S['fluid'].items():
    w(f"    --{n}-min: {num(dk * DMIN / R)};\n    --{n}-max: {num(dk)};")
w("  }\n}")

THEME = """  --text-2: color-mix(in srgb, var(--text) var(--tone-muted), transparent);
  --text-3: color-mix(in srgb, var(--text) var(--tone-faint), transparent);
  --background-skeleton: color-mix(in srgb, currentcolor 10%, transparent);
  --focus: var(--text);
  --selection-background: var(--text);
  --selection-text: var(--background);
  --dot-color: var(--text);
  --button-background: transparent;
  --button-border: transparent;
  --button-text: var(--text);
  --button-background-hover: transparent;
  --button-border-hover: transparent;
  --button-text-hover: var(--text);
  --button-2-background: transparent;
  --button-2-border: var(--border);
  --button-2-text: var(--text);
  --button-2-background-hover: transparent;
  --button-2-border-hover: var(--text);
  --button-2-text-hover: var(--text);
  --link-text: var(--text);
  --link-border: transparent;
  --link-text-hover: var(--text);
  --link-border-hover: transparent;"""
w(f"""/* Color themes. dark (the default: black, stone text, taupe for the big type), light (stone, black text),
   mustard (News) and teal (Contact): black text at full, half and 30 %; brand: red, black text. */
:root,
.theme-dark,
.theme-light .theme-invert,
.theme-mustard .theme-invert,
.theme-teal .theme-invert {{
  color-scheme: dark;
  --background: var(--black);
  --background-2: color-mix(in srgb, var(--stone) 6%, var(--black));
  --background-3: color-mix(in srgb, var(--stone) 12%, var(--black));
  --text: var(--stone);
  --border: color-mix(in srgb, var(--text) var(--tone-muted), transparent);
  --heading-accent: var(--taupe);
{THEME}
}}
.theme-light,
.theme-mustard,
.theme-teal,
.theme-brand,
.theme-dark .theme-invert {{
  color-scheme: light;
  --background: var(--stone);
  --background-2: color-mix(in srgb, var(--black) 6%, var(--stone));
  --background-3: color-mix(in srgb, var(--black) 12%, var(--stone));
  --text: var(--black);
  --border: color-mix(in srgb, var(--text) var(--tone-faint), transparent);
  --heading-accent: var(--text);
{THEME}
}}
.theme-mustard {{
  --background: var(--mustard);
  --background-2: color-mix(in srgb, var(--black) 6%, var(--mustard));
  --background-3: color-mix(in srgb, var(--black) 12%, var(--mustard));
}}
.theme-teal {{
  --background: var(--teal);
  --background-2: color-mix(in srgb, var(--black) 6%, var(--teal));
  --background-3: color-mix(in srgb, var(--black) 12%, var(--teal));
}}
.theme-brand {{
  --background: var(--red);
  --background-2: color-mix(in srgb, var(--black) 6%, var(--red));
  --background-3: color-mix(in srgb, var(--black) 12%, var(--red));
}}
/* The page's own colour */
.accent-red {{
  --page-accent: var(--red);
}}
.accent-mustard {{
  --page-accent: var(--mustard);
}}
.accent-teal {{
  --page-accent: var(--teal);
}}
:root,
[class*="theme-"] {{
  background-color: var(--background);
  color: var(--text);
}}""")
w(open(os.path.join(HERE, 'reset.css')).read().rstrip())
w("/* Text styles: GENERATED. A text style lives only here. */")
tag = {'text-main': 'body,\n', 'h1': 'h1,\n', 'h2': 'h2,\n', 'h3': 'h3,\nh4,\nh5,\nh6,\n'}
for n, t in S['text'].items():
    cls = '.text-style-' + (n[5:] if n.startswith('text-') else n)
    size = f"max(var(--{n}-floor), var(--{n}))" if n in S['floors'] else f"var(--{n})"
    w(f"{tag.get(n, '')}{cls} {{\n  font-family: var(--{n}-font-family);\n  font-size: {size};\n"
      f"  font-weight: var(--{n}-font-weight);\n  line-height: var(--{n}-line-height);\n"
      f"  letter-spacing: var(--{n}-letter-spacing);\n  text-transform: var(--{n}-text-transform);\n"
      f"  text-wrap: var(--{n}-text-wrap);\n  --_margin-top: var(--{n}-margin-top);\n"
      f"  --_margin-bottom: var(--{n}-margin-bottom);\n}}")
w("""/* Text trim: a text box runs from the cap top of its first line to the baseline of its last */
h1,
h2,
h3,
h4,
h5,
h6,
p,
[class*="text-style-"] {
  text-box: trim-both cap alphabetic;
}""")
dest = os.path.join(HERE, '..', 'src', 'styles', 'base.css')
open(dest, 'w').write('\n'.join(out) + '\n')
print('base.css written,', sum(1 for _ in open(dest)), 'lines')
